import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';

const root=process.env.MAKHEX_PREVIEW_URL??'http://127.0.0.1:4399';
const chrome=process.env.CHROME_BIN??'/usr/bin/google-chrome';
const browser=await chromium.launch({executablePath:chrome,headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']});
const page=await browser.newPage({viewport:{width:1280,height:800}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
const waitCount=async n=>page.waitForFunction(v=>Number(document.querySelector('[data-cart-count]')?.textContent)===v,n,{timeout:10000});
try{
 await page.goto(root+'/projects/mosaico-learning-assistant/',{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('.build11-approved-hero img').count(),1);
 assert.equal(await page.locator('.build11-approved-hero img').first().evaluate(e=>e.complete&&e.naturalWidth>150),true);
 assert.equal(await page.locator('.project-demo-local video').count(),1);
 assert.equal(await page.locator('.project-demo-local video source[src="/demo/build11-en-concept.mp4"]').count(),1);
 assert.equal(await page.locator('.project-demo-stills img').count(),3);
 assert.equal(await page.locator('.build11-approved-gallery img').count(),4,'Approved hero and three English workflow images must render');
 assert.equal(await page.locator('.project-demo-local video').evaluate(e=>e.canPlayType('video/mp4')!==''),true);
 await page.locator('[data-cart-add-all="mosaico-learning-assistant"]').click();
 await waitCount(2);
 await page.goto(root+'/cart/',{waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 assert.match(await page.locator('.cart-lines').innerText(),/Mosaico/);
 assert.match(await page.locator('[data-cart-total]').innerText(),/Price pending/);
 assert.equal(await page.locator('.cart-checkout-disabled').isDisabled(),true);
 assert.equal(await page.locator('.cart-line').count(),2,'Combo kit + data cable should be two items');
 await page.goto(root+'/projects/mosaico-learning-assistant/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-cart-add-plan="mosaico-learning-assistant"]').click();
 await waitCount(4);
 await page.goto(root+'/cart/',{waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 assert.equal(await page.locator('.cart-line').count(),4,'Four individual research BOM items expected');
 assert.doesNotMatch(await page.locator('.cart-lines').innerText(),/ESP-Mosaico Vision Combo Kit/,'Selecting modules must remove duplicate bundle');
 await page.goto(root+'/projects/mosaico-learning-assistant/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-cart-add-all="mosaico-learning-assistant"]').click();
 await waitCount(2);
 await page.goto(root+'/cart/',{waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 assert.equal(await page.locator('.cart-line').count(),2,'Switching back to bundle must remove individual modules');
 await page.locator('[data-cart-clear]').click();
 await waitCount(0);
 await page.goto(root+'/projects/espnow-remote/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-cart-add-all="espnow-remote"]').click();
 await waitCount(4);
 await page.goto(root+'/cart/',{waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 assert.equal(await page.locator('.cart-line').count(),2);
 assert.deepEqual((await page.locator('.cart-qty').evaluateAll(els=>els.map(e=>Number(e.value)))).sort((a,b)=>a-b),[2,2]);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 assert.equal(await page.locator('.cart-line').count(),2,'Persisted cart lost');
 await page.locator('[data-cart-clear]').click();
 await waitCount(0);
 await page.goto(root+'/projects/smart-desk-button/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-cart-add-all="smart-desk-button"]').click();
 await page.waitForFunction(()=>Number(document.querySelector('[data-cart-count]')?.textContent)>0);
 const before=Number(await page.locator('[data-cart-count]').first().innerText());
 await page.goto(root+'/projects/rgb-matrix-clock/',{waitUntil:'domcontentloaded'});
 await page.locator('[data-cart-add-all="rgb-matrix-clock"]').click();
 await page.waitForFunction(n=>Number(document.querySelector('[data-cart-count]')?.textContent)>n,before);
 await page.goto(root+'/cart/',{waitUntil:'domcontentloaded'});
 await page.locator('.cart-line').first().waitFor();
 const leds=page.locator('.cart-line').filter({hasText:'WS2812B Programmable LEDs'});
 assert.equal(await leds.count(),2,'8-LED ring and 8x8 LED matrix were collapsed together');
 assert.equal(errors.length,0,errors.join('; '));
 console.log('PASS: real browser Build 11 photo+video, add-all, correct ESP-NOW qty, cart persistence, distinct WS2812 options, checkout disabled');
}finally{await browser.close()}
