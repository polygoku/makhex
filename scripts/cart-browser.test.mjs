 assert.equal(recorded.lines.length,7);
 assert.equal(recorded.lines.find(p=>p.slug==='feetech-hd1910').quantity,15);
 assert.equal(recorded.lines.find(p=>p.slug==='microduck-speaker-3525').quantity,1);
 assert(recorded.lines.every(p=>!['microduck-hat','radxa-zero-3w','microduck-printed-parts','microduck-fasteners','amp20-servo-cables','microduck-wiring-kit'].includes(p.slug)));
